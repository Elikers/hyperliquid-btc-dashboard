"""Evaluate captured public BTC candles with seven-factor research only.

Reads artifacts generated by capture_public_btc.py. No external network,
Discord sends, trading decisions, or secret keys.
"""
import json
from pathlib import Path
from datetime import datetime, timezone

from research.parity_checks import TF_MS
from research.pipeline import calculate_research_candidate
from research.btc_only_lab import evaluate_btc_only_lab
from research.classic_macro_off import evaluate_classic_macro_off
from research.cross_timeframe_audit import audit_cross_timeframe


def score_snapshots(folder="capture-output"):
    directory=Path(folder)
    loaded={}
    for timeframe in TF_MS:
        path=directory/f"btc_{timeframe}.json"
        d=json.loads(path.read_text(encoding="utf-8"))
        if d.get("timeframe")!=timeframe or d.get("coin")!="BTC":
            raise ValueError(f"Wrong market in {path}")
        if d.get("discordEligible") is not False:
            raise ValueError("Research-data safety flag missing")
        loaded[timeframe]=d
    # All three snapshots must be from one coherent observation instant,
    # never a mixture of stale/new capture runs near a candle boundary.
    capture_times={loaded[tf].get("capturedAtUtc") for tf in TF_MS}
    if len(capture_times)!=1 or None in capture_times:
        raise RuntimeError("Mixed observation timestamps across BTC snapshots")
    # Before evaluating any confluence, prove that overlapping 30m/1h bars
    # agree with the independently returned 15m exchange candle feed.
    integrity=audit_cross_timeframe({
        tf:loaded[tf]["closedCandles"] for tf in ("15m","30m","1h")
    })
    if not integrity["passed"]:
        raise RuntimeError("Cross-timeframe BTC candle disagreement: "+str(integrity["timeframes"]))
    evidence={}
    lab_evidence={}
    macro_off_evidence={}
    for timeframe in TF_MS:
        d=loaded[timeframe]
        captured=datetime.fromisoformat(d["capturedAtUtc"])
        if captured.tzinfo is None:
            raise ValueError("Capture time must be UTC offset-aware")
        sampled_at=int(captured.timestamp()*1000)
        value=calculate_research_candidate(d["closedCandles"],
            loaded["15m"]["closedCandles"],timeframe=timeframe,
            current_ms=sampled_at)
        if value["discordEligible"] or value["researchDecision"]["discordEligible"]:
            raise RuntimeError("Research gate failed")
        evidence[timeframe]=value
        # Independent BTC-only Lab is separately labeled, unverified and not
        # eligible for Discord; Classic calculation and public site unchanged.
        lab=evaluate_btc_only_lab(d["closedCandles"],
            loaded["15m"]["closedCandles"],timeframe=timeframe,
            current_ms=sampled_at)
        if lab["discordEligible"] or lab["originalViprasolVerified"]:
            raise RuntimeError("Unverified Lab must never enable alerts")
        lab_evidence[timeframe]=lab
        macro_off=evaluate_classic_macro_off(d["closedCandles"],
            loaded["15m"]["closedCandles"],timeframe=timeframe,
            current_ms=sampled_at)
        if macro_off["discordEligible"] or macro_off["originalViprasolVerified"]:
            raise RuntimeError("Macro-OFF Classic must remain research only")
        macro_off_evidence[timeframe]=macro_off
    return {"kind":"public_btc_seven_factor_forward_research",
            "capturedAtUtc":loaded["15m"]["capturedAtUtc"],
            "timeframes":evidence,"candleIntegrity":integrity,
            "btcOnlyLab":lab_evidence,
            "viprasolClassicMacroOff":macro_off_evidence,
            "originalViprasolVerified":False,
            "discordEligible":False,"liveSignalAlerts":False,
            "limitations":["No original CME_MINI:NQ1! factor",
                           "No exact TradingView VWAP or barmerge parity"]}


def main():
    results=score_snapshots()
    target=Path("capture-output/research_candidates.json")
    target.write_text(json.dumps(results,indent=2)+"\n",encoding="utf-8")
    for tf, item in results["candleIntegrity"]["timeframes"].items():
        print(f"OHLCV integrity {tf}: {item['complete_groups']} full groups,"
              f" {item['mismatch_count']} mismatches")
    for tf, d in results["timeframes"].items():
        print(f"{tf}: bull {d['bullScoreSeven']}/7, bear {d['bearScoreSeven']}/7,"
              f" raw cross={d['rawCrossover'] or 'none'};"
              " unverified Discord alerts OFF")


if __name__=="__main__":
    main()
