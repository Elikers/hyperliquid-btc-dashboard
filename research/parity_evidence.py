"""Audit independently collected Viprasol reference signals.

Reference events must come from the original Pine configuration rather than
being generated by the research engine itself. Passing sample comparisons
NEVER authorizes live Discord trade alerts or automatic trading.
"""
from __future__ import annotations
from math import isfinite
from typing import Mapping, Sequence

TIMEFRAMES = ("15m", "30m", "1h")
REQUIRED_PRICES = ("entry", "stop", "tp1", "tp2", "tp3")


def _valid_event(event: Mapping) -> tuple:
    tf = event["timeframe"]
    side = event["side"]
    timestamp = int(event["close_ms"])
    if tf not in TIMEFRAMES or side not in ("LONG", "SHORT") or timestamp <= 0:
        raise ValueError("invalid reference event identity")
    prices = [float(event[key]) for key in REQUIRED_PRICES]
    if any(not isfinite(value) or value <= 0 for value in prices):
        raise ValueError("invalid reference event prices")
    entry, stop, tp1, tp2, tp3 = prices
    if side == "LONG" and not stop < entry < tp1 < tp2 < tp3:
        raise ValueError("invalid LONG price ladder")
    if side == "SHORT" and not stop > entry > tp1 > tp2 > tp3:
        raise ValueError("invalid SHORT price ladder")
    return tf, side, timestamp


def _index(events):
    result = {}
    for event in events:
        key = _valid_event(event)
        if key in result:
            raise ValueError("duplicate signal event: " + str(key))
        result[key] = event
    return result


def audit_references(
    original_events: Sequence[Mapping],
    candidate_events: Sequence[Mapping],
    *,
    max_price_delta: float = 0.1,
    source_independent: bool = False,
    settings_matched: bool = False,
    all_closed_bars_compared: bool = False,
) -> dict:
    """Compare all shared entry/exit prices, missing trades, and extra trades.

    Timing tolerance is zero. An event on a different bar is a distinct event.
    A zero-event sample is never validation evidence. Caller-provided provenance
    declarations do not themselves verify their truth; this is a research audit.
    """
    if not isfinite(max_price_delta) or max_price_delta < 0:
        raise ValueError("invalid price tolerance")
    reference = _index(original_events)
    candidate = _index(candidate_events)
    shared = reference.keys() & candidate.keys()
    missing = sorted(reference.keys() - candidate.keys())
    extra = sorted(candidate.keys() - reference.keys())
    differences = []
    for key in sorted(shared):
        expected, actual = reference[key], candidate[key]
        for field in REQUIRED_PRICES:
            ref_price, candidate_price = float(expected[field]), float(actual[field])
            distance = abs(ref_price - candidate_price)
            if distance > max_price_delta:
                differences.append({
                    "timeframe": key[0], "side": key[1], "close_ms": key[2],
                    "field": field, "reference": ref_price,
                    "candidate": candidate_price, "absolute_difference": distance,
                })
    by_timeframe = {}
    for tf in TIMEFRAMES:
        n_ref = sum(key[0] == tf for key in reference)
        n_candidate = sum(key[0] == tf for key in candidate)
        n_shared = sum(key[0] == tf for key in shared)
        by_timeframe[tf] = {
            "reference_events": n_ref,
            "candidate_events": n_candidate,
            "matched_events": n_shared,
            "missing_events": sum(key[0] == tf for key in missing),
            "extra_events": sum(key[0] == tf for key in extra),
            "price_mismatches": sum(row["timeframe"] == tf for row in differences),
            "precision": n_shared/n_candidate if n_candidate else None,
            "recall": n_shared/n_ref if n_ref else None,
        }
    sample_exact = bool(reference) and not missing and not extra and not differences
    blockers = []
    if not source_independent:
        blockers.append("REFERENCE_NOT_INDEPENDENT")
    if not settings_matched:
        blockers.append("CONFIGURATION_NOT_VERIFIED")
    if not all_closed_bars_compared:
        blockers.append("ABSENCE_OF_SIGNALS_NOT_CHECKED")
    if not sample_exact:
        blockers.append("SIGNAL_OR_PRICE_MISMATCH_OR_EMPTY_REFERENCE")
    if any(by_timeframe[tf]["reference_events"] == 0 for tf in TIMEFRAMES):
        blockers.append("REFERENCE_MISSING_TIMEFRAME_EVIDENCE")
    return {
        "mode": "VIPRASOL_CLASSIC_MACRO_OFF",
        "source_evidence_complete": not blockers,
        "blockers": blockers,
        "by_timeframe": by_timeframe,
        "missing": [list(key) for key in missing],
        "extra": [list(key) for key in extra],
        "price_differences": differences,
        "sample_exact": sample_exact,
        "full_original_viprasol_verified": False,
        "discord_eligible": False,
        "auto_trading_enabled": False,
        "note": "Sample agreement cannot certify live data or profitability.",
    }
